# ---------------------------------------------------------------- нормализация

# Латинские буквы-двойники и цифры → кириллица.
_TO_CYR = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "i": "и", "k": "к", "m": "м", "o": "о",
    "p": "р", "t": "т", "u": "и", "x": "х", "y": "у",
    "0": "о", "1": "и", "3": "з", "4": "ч", "6": "б",
    "ё": "е",
})
# Кириллица-двойники и цифры → латиница (для смешанных «suкa»).
_TO_LAT = str.maketrans({
    "а": "a", "в": "b", "е": "e", "ё": "e", "к": "k", "м": "m", "н": "h", "о": "o", "р": "p",
    "с": "c", "т": "t", "у": "y", "х": "x", "и": "u",
    "0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t",
})
_NOT_CYR = re.compile(r"[^а-я]")
_NOT_LAT = re.compile(r"[^a-z]")
_REPEATS = re.compile(r"(.)\1+")
_SEPARATORS = re.compile(r"[\s_.\-]+")


def _collapse(text: str) -> str:
    return _REPEATS.sub(r"\1", text)


def _cyr_form(text: str) -> str:
    return _collapse(_NOT_CYR.sub("", text.lower().translate(_TO_CYR)))


def _lat_form(text: str) -> str:
    return _collapse(_NOT_LAT.sub("", text.lower().translate(_TO_LAT)))


def _has_root(form: str, roots: tuple[str, ...], allowed: tuple[str, ...]) -> bool:
    for word in allowed:
        form = form.replace(word, "")
    return any(root in form for root in roots)


def is_profane(text: str) -> bool:
    """True, если в тексте есть мат или оскорбление (с учётом попыток обхода)."""
    if _has_root(_cyr_form(text), _CYR_ROOTS, _CYR_ALLOWED):
        return True
    if _has_root(_lat_form(text), _LAT_ROOTS, _LAT_ALLOWED):
        return True
    for token in _SEPARATORS.split(text):
        if _cyr_form(token) in _CYR_WORDS or _lat_form(token) in _LAT_WORDS:
            return True
    return False
